import { z } from "zod";

/**
 * Danh mục khu vực thực tế: Trường Đại học Công nghệ (UET) — ĐHQGHN tại Hoà Lạc
 * Các công trình:
 * - UET1: 5 tầng (Tầng 1 -> 5)
 * - UET2: 5 tầng (Tầng 1 -> 5)
 * - UET3: 5 tầng (Tầng 1 -> 5)
 * - UET4: 4 tầng (Tầng 1 -> 4)
 * - Nhà đa năng (ĐN): 2 tầng (Tầng 1 -> 2)
 * - 3 Cổng trường: Cổng 1 (Chính), Cổng 2 (Phụ Tây), Cổng 3 (Dịch vụ / KTX)
 *
 * 10 nút cảm biến IoT (khói SPS30 + PIR) bố trí tại các điểm nóng nguy cơ cao:
 * - UET1-3CT, UET1-5WC
 * - UET2-3CT, UET2-5WC
 * - UET3-2HL, UET3-4WC
 * - UET4-2CT, UET4-4ST
 * - DN-1WC, DN-2HL
 */

export const buildings = [
  "UET1",
  "UET2",
  "UET3",
  "UET4",
  "DN",
  "CONG",
] as const;
export type Building = (typeof buildings)[number] | string;

export const zoneSchema = z.object({
  code: z.string(),
  name: z.string(),
  building: z.string(),
  floor: z.number().int().min(1).max(5),
  x: z.number().min(0).max(1000),
  y: z.number().min(0).max(560),
  sensor_id: z.string().nullable(),
  qr_id: z.string(),
  sensor_state: z.enum(["normal", "suspected", "offline", "unknown"]),
  presence: z.boolean().nullable(),
});

export type Zone = z.infer<typeof zoneSchema>;

export const zoneListSchema = z.object({
  items: z.array(zoneSchema),
  coordinates_status: z.enum(["provisional", "approved"]),
});

