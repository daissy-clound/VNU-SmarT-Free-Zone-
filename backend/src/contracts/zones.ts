import { z } from "zod";

/**
 * Danh mục 20 khu vực & 10 nút cảm biến KTX ĐHQGHN
 * - 2 toà A và B, mỗi toà 6 tầng
 * - 10 nút cảm biến (có cảm biến khói SPS30 + PIR):
 *   A2-WC, A3-CTT, A4-HL, A5-CTD, A6-ST
 *   B2-WC, B3-CTT, B4-HL, B5-CTD, B6-ST
 * - 10 vị trí mã QR công cộng:
 *   Sảnh (SANH), Nhà xe (NX), Căng-tin (CT), Hành lang giữa (HLG)
 */
export const zoneSchema = z.object({
  code: z.string(),
  name: z.string(),
  building: z.enum(["A", "B"]),
  floor: z.number().int().min(1).max(6),
  x: z.number().min(0).max(1000),
  y: z.number().min(0).max(560),
  sensor_id: z.string().nullable(),
  qr_id: z.string(),
  sensor_state: z.enum(["normal", "suspected", "offline", "unknown"]),
  presence: z.boolean().nullable(),
});

export type Zone = z.infer<typeof zoneSchema>;

export const zoneListSchema = z.object({
  items: z.array(zoneSchema),
  coordinates_status: z.enum(["provisional", "approved"]),
});

